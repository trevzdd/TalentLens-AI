"""Synthetic HR datasets for the demo.

IMPORTANT: these are generated by simple rules written by the author.
A model trained on them recovers those rules; its metrics are NOT evidence
about real employees. Column names match the public IBM HR Analytics
Attrition dataset so the real file can be dropped in.
"""
from __future__ import annotations

import numpy as np
import pandas as pd


def generate_employees(n: int = 1500, seed: int = 7) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    dept = rng.choice(["Sales", "R&D", "HR", "Operations"], n, p=[0.30, 0.40, 0.08, 0.22])
    gender = rng.choice(["Female", "Male"], n, p=[0.45, 0.55])
    age = np.clip(rng.normal(36, 8, n), 20, 62).round().astype(int)
    years = np.clip(rng.gamma(2.0, 2.5, n), 0, 30).round().astype(int)
    income = np.clip(rng.lognormal(8.6, 0.45, n) + years * 120, 1800, 20000).round().astype(int)
    since_promo = np.minimum(np.clip(rng.gamma(1.5, 1.6, n).round().astype(int), 0, 15), years)
    overtime = rng.choice(["Yes", "No"], n, p=[0.28, 0.72])
    job_sat = rng.choice([1, 2, 3, 4], n, p=[0.15, 0.20, 0.35, 0.30])
    wlb = rng.choice([1, 2, 3, 4], n, p=[0.06, 0.24, 0.50, 0.20])
    dist = np.clip(rng.gamma(1.6, 5.0, n), 1, 29).round().astype(int)

    # Hand-written attrition rule (no use of gender or age).
    logit = (
        -2.2
        + 1.1 * (overtime == "Yes")
        - 0.45 * (job_sat - 2.5)
        - 0.30 * (wlb - 2.5)
        - 0.00035 * (income - 6000)
        + 0.10 * since_promo
        - 0.06 * years
        + 0.025 * dist
    )
    p = 1 / (1 + np.exp(-logit))
    attrition = np.where(rng.random(n) < p, "Yes", "No")

    return pd.DataFrame(
        {
            "EmployeeID": np.arange(1, n + 1),
            "Age": age,
            "Gender": gender,
            "Department": dept,
            "MonthlyIncome": income,
            "YearsAtCompany": years,
            "YearsSinceLastPromotion": since_promo,
            "OverTime": overtime,
            "JobSatisfaction": job_sat,
            "WorkLifeBalance": wlb,
            "DistanceFromHome": dist,
            "Attrition": attrition,
        }
    )


SOURCE_PARAMS = {
    # source: (share of applicants, P(screen), P(interview|screen), P(offer|interview), P(hire|offer))
    "Referral": (0.20, 0.80, 0.60, 0.40, 0.85),
    "LinkedIn": (0.35, 0.55, 0.45, 0.30, 0.75),
    "Job Board": (0.30, 0.40, 0.35, 0.25, 0.70),
    "Company Website": (0.15, 0.50, 0.40, 0.30, 0.80),
}


def generate_hiring_funnel(n: int = 900, seed: int = 11) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    sources = list(SOURCE_PARAMS)
    shares = [SOURCE_PARAMS[s][0] for s in sources]
    src = rng.choice(sources, n, p=shares)
    start = pd.Timestamp("2025-01-01")
    applied = start + pd.to_timedelta(rng.integers(0, 330, n), unit="D")

    cols = {"Screening_Date": [], "Interview_Date": [], "Offer_Date": [], "Hired_Date": []}
    delay_scale = [(3, 1.5), (7, 3.0), (6, 2.5), (5, 2.0)]  # gamma shape, scale per step
    for i in range(n):
        probs = SOURCE_PARAMS[src[i]][1:]
        current = applied[i]
        alive = True
        for (key, pr, (shape, scale)) in zip(cols, probs, delay_scale):
            if alive and rng.random() < pr:
                current = current + pd.Timedelta(days=int(max(1, rng.gamma(shape, scale))))
                cols[key].append(current)
            else:
                alive = False
                cols[key].append(pd.NaT)

    df = pd.DataFrame({"CandidateID": [f"A{i:04d}" for i in range(1, n + 1)],
                       "Source": src, "Applied_Date": applied})
    for k, v in cols.items():
        df[k] = v
    return df
