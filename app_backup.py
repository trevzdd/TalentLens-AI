# Attrition model
# =====================================================================
emp_df, emp_warn, emp_err = safe_load(load_employees, emp_src)
result = None
if emp_df is not None and not emp_err:
    try:
        result = cached_train(emp_df)
    except Exception as e:
        emp_err = str(e)

with tab_attr:
    st.subheader("Employee attrition model (logistic regression)")
    if emp_err:
        st.error(f"Could not use the employees file: {emp_err}")
    elif emp_df is None:
        st.info("Upload an employees CSV in the sidebar, or switch to the sample.")
    else:
        if emp_is_sample:
            st.warning(
                "Synthetic data. The leaving probability was generated by a rule I wrote, so the model "
                "re-discovers that rule. These results demonstrate the method, not real behaviour. "
                "Upload the public IBM HR Analytics Attrition file to see a realistic (and weaker) result.")
        for w in emp_warn:
            st.warning(w)

        m = result["metrics"]
        a, b, c, d = st.columns(4)
        a.metric("Employees", len(emp_df))
        b.metric("Attrition rate", f"{result['attrition_rate'] * 100:.1f}%")
        c.metric("Train / test", f"{result['n_train']} / {result['n_test']}")
        d.metric("ROC AUC (test)", m["ROC AUC (test)"])

        st.markdown("**Held-out test metrics**")
        st.dataframe(pd.DataFrame({"Metric": list(m), "Value": list(m.values())}), hide_index=True)
        if m["Accuracy"] < m["Baseline accuracy (always 'stays')"]:
            st.info(
                "Accuracy is lower than the baseline of always predicting 'stays'. That is expected here: "
                "leavers are a minority and the model is tuned to catch them (higher recall) at the cost of "
                "more false alarms (lower precision). With imbalanced classes, accuracy alone is misleading, "
                "so look at recall, precision and ROC AUC.")

        cm = result["confusion"]
        st.markdown("**Confusion matrix (test set)**")
        st.dataframe(pd.DataFrame(
            {"Predicted stays": [cm["TN"], cm["FN"]], "Predicted leaves": [cm["FP"], cm["TP"]]},
            index=["Actually stayed", "Actually left"]))

        st.markdown("**What the model relies on**")
        imp = result["importance"]
        st.bar_chart(imp.set_index("Feature")["Coefficient"])
        st.dataframe(imp, hide_index=True)
        st.caption(
            "Numeric features are standardised, so coefficients are comparable. Odds ratio above 1 means "
            "higher risk of leaving; below 1 means lower. This shows association in this dataset, not cause.")
        st.caption("Gender and Age are **not** used as features. They are used only in the Fairness audit.")

# =====================================================================
# Fairness audit
# =====================================================================
with tab_fair:
    st.subheader("Fairness audit of the attrition model")
    if result is None or emp_df is None:
        st.info("Load employee data first (see the Attrition model tab).")
    else:
        test = emp_df.loc[result["test_index"]]
        options = [c for c in AUDIT_COLUMNS if c in test.columns]
        if not options:
            st.info("Add a Gender and/or Age column to the employees file to run the audit.")
        else:
            attr = st.selectbox("Compare groups by", options)
            groups = age_groups(test["Age"]) if attr == "Age" else test[attr].astype(str)
            rep = group_report(result["y_test"], result["y_pred"], groups.to_numpy())
            st.dataframe(rep, hide_index=True)
            ratio = flag_rate_ratio(rep)
            if ratio is None:
                st.info("Not enough large groups to compute a ratio.")
            else:
                st.metric("Flag-rate ratio (lowest / highest group)", ratio)
                if ratio < 0.8:
                    st.warning(
                        "Ratio below 0.8: groups are flagged at noticeably different rates. "
                        "Investigate the cause before using the model for anything.")
                else:
                    st.success("Ratio is 0.8 or higher: flag rates are similar across groups.")
            if rep["Small group"].any():
                st.caption("Groups marked 'Small group' (fewer than 20 people) are excluded from the ratio; "
                           "their rates are unreliable.")
            st.caption(
                "The 0.8 threshold comes from the US 'four-fifths' rule of thumb and is only a screening "
                "heuristic. Also compare true/false positive rates: equal flag rates can still hide unequal "
                "error rates. Passing this check does not prove a model is fair; it only checks one attribute "
                "at a time on one test set.")

