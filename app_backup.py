# =====================================================================
# Pipeline
# =====================================================================
cand_df, cand_warn, cand_err = safe_load(load_candidates, cand_src)
filtered = pd.DataFrame()

with tab_pipe:
    if cand_err:
        st.error(f"Could not read the candidates file: {cand_err}")
    elif cand_df is None:
        st.info("Upload a candidates CSV in the sidebar, or switch to the sample.")
    elif cand_df.empty:
        st.error("The candidates file has no rows.")
    else:
        for w in cand_warn:
            st.warning(w)
        with st.expander("Filters", expanded=True):
            c1, c2, c3 = st.columns(3)
            statuses_all = [s for s in STATUS_ORDER if s in set(cand_df["Status"])] + sorted(
                set(cand_df["Status"]) - set(STATUS_ORDER))
            statuses = c1.multiselect("Status", statuses_all, default=statuses_all)
            sources_all = sorted(cand_df["Source"].unique())
            sources = c2.multiselect("Source", sources_all, default=sources_all)
            top = int(max(10, cand_df["Experience"].max()))
            lo, hi = c3.slider("Years of experience", 0, top, (0, top))
            search = st.text_input("Search name or skills")

        filtered = cand_df[
            cand_df["Status"].isin(statuses) & cand_df["Source"].isin(sources)
            & cand_df["Experience"].between(lo, hi)
        ].copy()
        if search:
            filtered = filtered[
                filtered["Name"].str.contains(search, case=False, na=False)
                | filtered["Skills"].str.contains(search, case=False, na=False)
            ]

        a, b, c, d = st.columns(4)
        a.metric("Candidates", len(filtered))
        b.metric("Interviews", int((filtered["Status"] == "Interview").sum()))
        c.metric("Offers", int((filtered["Status"] == "Offer").sum()))
        d.metric("Hired", int((filtered["Status"] == "Hired").sum()))

        left, right = st.columns(2)
        if filtered.empty:
            st.write("No candidates match the filters.")
        else:
            with left:
                st.subheader("Where candidates are now")
                counts = filtered["Status"].value_counts()
                order = [s for s in STATUS_ORDER if s in counts.index] + [
                    s for s in counts.index if s not in STATUS_ORDER]
                names = numbered(order)
                st.bar_chart(counts.reindex(order).rename(index=names))
                st.caption("Current status only. See the Hiring funnel tab for conversion between stages.")
            with right:
                st.subheader("Candidates by source")
                st.bar_chart(filtered["Source"].value_counts())
            st.dataframe(filtered, hide_index=True)
            st.download_button("Download filtered candidates (CSV)",
                               filtered.to_csv(index=False).encode("utf-8"),
                               "filtered_candidates.csv", "text/csv")

# =====================================================================
# Job matching
# =====================================================================
